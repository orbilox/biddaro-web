// ─── بيانات SEO العربية لدولة الإمارات العربية المتحدة ────────────────────────────
// تدعم صفحات /uae/ar/hire/[category]/[emirate] و /uae/ar/hire/[category]/[emirate]/[city]
// جميع المحتوى باللغة العربية مع الاحتفاظ بالـ slugs الإنجليزية للروابط

export interface CityEntry {
  name: string;     // "دبي مارينا"
  slug: string;     // "dubai-marina"  (English slug for URL)
}

export interface UAELocationAR {
  name: string;     // "دبي"
  slug: string;     // "dubai"
  capital: string;  // "مدينة دبي"
  region: string;   // "إمارة"
  cities: CityEntry[];
}

export interface FAQ {
  q: string;
  a: string;
}

export interface JobCategoryMetaAR {
  name: string;       // "مقاول عام"
  slug: string;       // "general-contractor"
  emoji: string;
  plural: string;     // "مقاولون عامون"
  shortDesc: string;
  longDesc: string;
  skills: string[];
  avgRate: string;    // "80–200 درهم / ساعة"
  faqs: FAQ[];        // {state} يُستبدل بالإمارة عند العرض
}

// ─── دوال مساعدة ─────────────────────────────────────────────────────────────

export function getUAELocationAR(slug: string): UAELocationAR | undefined {
  return UAE_LOCATIONS_AR.find(l => l.slug === slug);
}

export function getUAECategoryAR(slug: string): JobCategoryMetaAR | undefined {
  return UAE_JOB_CATEGORY_META_AR.find(c => c.slug === slug);
}

export function getUAECityAR(emirateSlug: string, citySlug: string): CityEntry | undefined {
  return getUAELocationAR(emirateSlug)?.cities.find(c => c.slug === citySlug);
}

