// ── HELPER FUNCTIONS ──────────────────────────────────────

export function getQuestion(slug: string): AskQuestion | undefined {
  return QUESTIONS.find((q) => q.slug === slug);
}

export function getQuestionsByCategory(category: QuestionCategory): AskQuestion[] {
  return QUESTIONS.filter((q) => q.category === category);
}

export function getFeaturedQuestions(): AskQuestion[] {
  return QUESTIONS.filter((q) => q.featured);
}

export function getRelatedQuestions(slug: string, limit = 4): AskQuestion[] {
  const q = getQuestion(slug);
  if (!q) return [];
  return q.relatedSlugs
    .map((s) => getQuestion(s))
    .filter((x): x is AskQuestion => !!x)
    .slice(0, limit);
}

export function getAllSlugs(): string[] {
  return QUESTIONS.map((q) => q.slug);
}

export function searchQuestions(query: string): AskQuestion[] {
  const lower = query.toLowerCase();
  return QUESTIONS.filter(
    (q) =>
      q.question.toLowerCase().includes(lower) ||
      q.tags.some((t) => t.includes(lower)) ||
      q.keywords.some((k) => k.includes(lower))
  );
}
